"""Validation of Theorem 2.2 (smoothness invariance of the sector bottleneck).

Statement.  Let F be a Qp-Foliation on a core X with d oriented edges and
junction digits a(e,e') in F_p^*.  Then

 (a) S_n = sum_chi G(chi-bar)/(p-1) * Tr(B_chi^n),   (B_chi)_{e,e'} = chi(a(e,e'));
 (b) G(chi_0) = -1 and |G(chi)| = sqrt(p) for every chi != chi_0, so no
     sector can be discarded;
 (c) under Hypothesis (H) the Hankel matrix of phi = psi o a-bar has rank
     >= p - 1, whatever the factorisation of p - 1.  Hence every edge-by-edge
     transfer-matrix representation over C needs dimension >= p - 1, and the
     sector-by-sector evaluation -- a block-diagonal transfer matrix of total
     dimension d(p-1) -- costs Theta(p * poly(n, d)) even when p - 1 is
     B-smooth.  Smoothness does not collapse the separation in this model.

Checks
------
1. (a) on K4 for smooth and non-smooth p and several n: brute-force walk
   enumeration == sector formula == direct (edge, digit) transfer matrix.
2. (b) Gauss-sum magnitudes for all characters.
3. (c) explicit Hankel submatrix on K4 (prefix words e0 -> e*, suffix words
   e' -> e1): coverage of F_p^* (Hypothesis (H)) and rank exactly p - 1,
   for smooth and non-smooth p alike.
4. The sector-by-sector transfer operator is block diagonal of size d(p-1)
   and reproduces S_n (it *is* a transfer matrix, so (c) applies to it).
"""
from __future__ import annotations

import math
import random

import numpy as np

from common import (K4, Report, cyclic_product, gauss_sum, is_smooth,
                    mult_char_table, open_product, prim_root, psi, random_digits,
                    rank, smoothness)

PRIMES = [17, 97, 23, 47, 59]  # 16 = 2^4, 96 = 2^5*3 smooth; 22, 46, 58 not 3-smooth


def brute_S(core, a, p, n):
    return sum(psi(cyclic_product(w, a, p), p) for w in core.closed_words(n))


def transfer_S(core, a, p, n):
    """Direct transfer matrix on states (e, y), y in F_p^*: dimension d(p-1)."""
    d = core.d
    D = d * (p - 1)
    T = np.zeros((D, D))
    for (e, f), x in a.items():
        for y in range(1, p):
            T[e * (p - 1) + (y - 1), f * (p - 1) + (y * x % p - 1)] = 1
    Tn = np.linalg.matrix_power(T, n)
    tot = 0
    for e in range(d):
        for y in range(1, p):
            tot += Tn[e * (p - 1) + 0, e * (p - 1) + (y - 1)] * psi(y, p)
    return tot


def hankel_rank(core, a, p, Lmax=18, full_check=False):
    """Hankel submatrix H[u, v] = psi(a-bar(uv)) on closed concatenations u.v.

    Prefixes u run over NB words e0 -> e*, suffixes v over NB words e' -> e1,
    with e* -> e' and e1 -> e0 NB, so every u.v is a closed NB word.  Words are
    generated by increasing length until the prefix/suffix products cover
    F_p^* (Hypothesis (H)) or Lmax is reached; one representative word is kept
    per product value (rows with equal prefix value are equal rows, which is
    checked explicitly when full_check=True).
    """
    e0 = 0
    e_star = core.succ[core.succ[e0][0]][0]
    e_prime = core.succ[e_star][0]
    e1 = [e for e in range(core.d) if core.allowed(e, e0) and e != e_prime][0]
    pre, suf, all_pre, all_suf = {}, {}, [], []
    for L in range(1, Lmax + 1):
        for w in core.nb_words(L, e0):
            if w[-1] == e_star:
                pre.setdefault(open_product(w, a, p), w)
                all_pre.append(w)
        for w in core.nb_words(L, e_prime):
            if w[-1] == e1:
                suf.setdefault(open_product(w, a, p), w)
                all_suf.append(w)
        if len(pre) == p - 1 and len(suf) == p - 1 and not full_check:
            break
    U, V = list(pre.values()), list(suf.values())
    H = np.array([[psi(cyclic_product(u + v, a, p), p) for v in V] for u in U])
    r = rank(H)
    r_full = None
    if full_check:
        Hf = np.array([[psi(cyclic_product(u + v, a, p), p) for v in all_suf] for u in all_pre])
        r_full = (rank(Hf), Hf.shape)
    return r, len(pre), len(suf), L, r_full


def main() -> None:
    rep = Report("Theorem 2.2 -- smoothness invariance of the sector bottleneck")
    rng = random.Random(2202)
    core = K4()
    for p in PRIMES:
        tag = f"p={p} (p-1 B-smooth with B={smoothness(p - 1)}; 3-smooth={is_smooth(p - 1, 3)})"
        g = prim_root(p)
        chi = mult_char_table(p, g)
        G = np.array([gauss_sum(chi[k], p) for k in range(p - 1)])
        a = random_digits(core, p, rng)

        # (a) decomposition
        ok, worst = True, 0.0
        for n in (3, 4, 5, 6, 7):
            sb = brute_S(core, a, p, n)
            ss = sum(G[(-k) % (p - 1)] / (p - 1) * np.trace(np.linalg.matrix_power(
                build_B(core, a, chi[k]), n)) for k in range(p - 1))
            st = transfer_S(core, a, p, n)
            err = max(abs(sb - ss), abs(sb - st))
            worst = max(worst, err)
            ok &= err < 1e-6 * max(1, abs(sb))
        rep.check(f"{tag}: (a) brute == sector formula == transfer matrix, n=3..7", ok,
                  f"max abs err={worst:.1e}")

        # (b) Gauss sums
        mags = np.abs(G)
        ok_b = abs(G[0] + 1) < 1e-9 and np.all(np.abs(mags[1:] - math.sqrt(p)) < 1e-9)
        rep.check(f"{tag}: (b) G(chi0)=-1, |G(chi)|=sqrt(p) for all {p - 2} others", ok_b)

        # (c) Hankel rank
        r, nX, nY, L, _ = hankel_rank(core, a, p)
        rep.check(f"{tag}: (c) Hypothesis (H) holds (prefix/suffix products cover F_p^*)",
                  nX == p - 1 and nY == p - 1, f"|X|={nX}, |Y|={nY}, word length <= {L}")
        rep.check(f"{tag}: (c) Hankel rank == p-1 = {p - 1}", r == p - 1, f"rank={r}")

        # 4. sector algorithm is a block-diagonal transfer matrix of size d(p-1)
        blocks = [build_B(core, a, chi[k]) for k in range(p - 1)]
        dim = sum(b.shape[0] for b in blocks)
        rep.check(f"{tag}: sector algorithm = block-diag transfer matrix of dim d(p-1)",
                  dim == core.d * (p - 1) >= p - 1, f"dim={dim}")
    # de-duplication sanity check on the full (non-deduplicated) submatrix
    p = 17
    a = random_digits(core, p, rng)
    r, nX, nY, L, (r_full, shape) = hankel_rank(core, a, p, Lmax=13, full_check=True)
    rep.check("p=17: full Hankel submatrix (all words, no de-dup) has the same rank",
              r_full == r == p - 1, f"full {shape[0]}x{shape[1]} rank={r_full}")
    rep.finish()


def build_B(core, a, chi_row):
    B = np.zeros((core.d, core.d), dtype=complex)
    for (e, f), x in a.items():
        B[e, f] = chi_row[x]
    return B


if __name__ == "__main__":
    main()
